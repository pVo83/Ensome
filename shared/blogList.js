export function getBlogPostUrl(slug) {
  return `/blog/${slug}`
}

function isNotCurrentPost(post, currentSlug) {
  return post.slug !== currentSlug
}

function sortByViewsDescending(postA, postB) {
  return postB.views - postA.views
}

function hasSharedTag(post, tags) {
  return post.tags?.some((tag) => tags.includes(tag))
}

export function getPopularPosts(posts, limit = 4, excludeSlug = "") {
  const otherPosts = posts.filter((post) => isNotCurrentPost(post, excludeSlug))

  return [...otherPosts].sort(sortByViewsDescending).slice(0, limit)
}

export function getRelatedPosts(posts, currentPost, limit = 3) {
  const currentTags = currentPost.tags ?? []
  const otherPosts = posts.filter((post) => isNotCurrentPost(post, currentPost.slug))
  const relatedByTags = otherPosts.filter((post) => hasSharedTag(post, currentTags))

  return (relatedByTags.length ? relatedByTags : otherPosts).slice(0, limit)
}
